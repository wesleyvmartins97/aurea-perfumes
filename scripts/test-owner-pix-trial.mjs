import assert from 'node:assert/strict';
import fs from 'node:fs';
import {ownerPixTrialActive,ownerPixTrialEligible,ownerPixTrialCartAllowed,ownerPixTrialPixUnit,OWNER_TRIAL_PRODUCT_ID,OWNER_TRIAL_PRICE,OWNER_TRIAL_ORIGINAL_PRICE,OWNER_TRIAL_ORIGINAL_PIX} from '../src/payments/owner-pix-trial.mjs';

const env={VALENZA_OWNER_PIX_TRIAL:'true',VALENZA_OWNER_PIX_TRIAL_UNTIL:'2026-10-15T21:00:00.000Z',VALENZA_OWNER_PIX_TRIAL_EMAIL:'wesleyvmartins97@gmail.com'};
const good={email:'wesleyvmartins97@gmail.com',email_verified:1};
const before=Date.parse('2026-10-15T18:00:00.000Z');
const after=Date.parse('2026-10-15T21:00:01.000Z');
assert.equal(ownerPixTrialActive(env,before),true);
assert.equal(ownerPixTrialActive(env,after),false,'Automatic rollback ends test without relying on operator');
assert.equal(ownerPixTrialActive({...env,VALENZA_OWNER_PIX_TRIAL:'false'},before),false);
assert.equal(ownerPixTrialEligible(good,env,before),true);
assert.equal(ownerPixTrialEligible({...good,email:'jjessitrindade@gmail.com'},env,before),false,'Even second admin cannot buy');
assert.equal(ownerPixTrialEligible({...good,email_verified:0},env,before),false);
assert.equal(ownerPixTrialEligible(null,env,before),false);
assert.equal(ownerPixTrialEligible(good,env,after),false);
assert.equal(ownerPixTrialEligible(good,{...env,VALENZA_OWNER_PIX_TRIAL_EMAIL:'attacker@gmail.com'},before),false);
assert.equal(ownerPixTrialCartAllowed([{id:'vulcan-baie',qty:1}],{id:'local-colatina'}),true);
assert.equal(ownerPixTrialCartAllowed([{id:'vulcan-baie',qty:2}],{id:'local-colatina'}),false);
assert.equal(ownerPixTrialCartAllowed([{id:'vulcan-baie',qty:1}],{id:'externo'}),false);
assert.equal(ownerPixTrialCartAllowed([{id:'vulcan-baie',qty:1},{id:'good-girl',qty:1}],{id:'local-colatina'}),false);
assert.equal(ownerPixTrialCartAllowed([{id:'other',qty:1}],{id:'local-colatina'}),false);
assert.equal(OWNER_TRIAL_PRICE,1);
assert.equal(OWNER_TRIAL_ORIGINAL_PRICE,289.90);
assert.equal(OWNER_TRIAL_ORIGINAL_PIX,275.41);
assert.equal(ownerPixTrialPixUnit({id:OWNER_TRIAL_PRODUCT_ID},true),1);
assert.equal(ownerPixTrialPixUnit({id:'outro'},true),null);
assert.equal(ownerPixTrialPixUnit({id:OWNER_TRIAL_PRODUCT_ID},false),null);
const worker=fs.readFileSync('src/worker.js','utf8');
const ui=fs.readFileSync('public/index.html','utf8');
const wrangler=fs.readFileSync('wrangler.jsonc','utf8');
const bridge=fs.readFileSync('src/payments/asaas-valenza.mjs','utf8');
assert.match(worker,/ownerPixTrialCartAllowed\(dados.items,shipping\)/,'Pix must enforce exactly one product and local Colatina shipping before inventory reservation');
assert.match(worker,/if\(ownerTrial&&!ownerPixTrialEligible\(u,env\)\)return resposta\(/,'Other customers cannot create payments');
assert.match(worker,/async function criarPagamentoCartao\(request,env\)\{[\s\S]{0,250}if\(ownerPixTrialActive\(env\)\)return resposta\(/,'No card purchase during trial');
assert.match(worker,/canonicalItems\(dados.items,env,\{ownerTrial\}\)/,'Server is price authority');
assert.match(worker,/ownerPixTrialPixUnit\(x,ownerTrial\)\?\?pixPrice\(x.price\)/,'Real Pix must be exactly R$1, not R$0.95');
assert.match(worker,/snap.ownerPixTrial&&it.id===OWNER_TRIAL_PRODUCT_ID\?OWNER_TRIAL_PRICE/,'D1 order unit price matches real Pix charge');
assert.match(bridge,/ownerPixTrial:ownerTrial/,'Restore can use owner test marker after expiry');
assert.match(ui,/valenzaOwnerPixTrial=ownerInfo\?\.eligible===true&&ownerInfo\?\.active===true/,'Price visible only after server authenticated owner');
assert.match(ui,/valenzaCartPixUnit\(x\)/);
assert.match(wrangler,/"VALENZA_OWNER_PIX_TRIAL": "true"/);
assert.match(wrangler,/"VALENZA_OWNER_PIX_TRIAL_UNTIL": "2026-10-15T21:00:00.000Z"/);
assert.match(worker,/"vulcan-baie":\{"name": "Vulcan Baie"[\s\S]{0,180}"price": 289\.9/,'Public catalog stays R$289.90');
const products=fs.readFileSync('public/products.js','utf8');
assert.match(products,/Vulcan Baie/,'Public product remains present');
assert.ok(!products.includes('owner-private-pix-verification'),'No global price override');
console.log('OK: private owner-only Asaas PIX R$1; authentic user, one unit, Colatina, card lock, auto rollback.');
