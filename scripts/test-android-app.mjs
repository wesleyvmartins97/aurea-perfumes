import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import {androidRoute,appClient} from '../src/android-app.mjs';
const origin='https://www.valenzaparfums.com.br';
const version=await androidRoute(new Request(origin+'/api/app/version')).json();
const apk=androidRoute(new Request(origin+'/api/app/download'));
const bytes=new Uint8Array(await apk.arrayBuffer());
assert.equal(createHash('sha256').update(bytes).digest('hex'),version.sha256);
assert.equal(apk.headers.get('Content-Type'),'application/vnd.android.package-archive');
assert.equal(Number(apk.headers.get('Content-Length')),bytes.length);
assert.equal(bytes[0],0x50);assert.equal(bytes[1],0x4b);
assert.equal(androidRoute(new Request(origin+'/api/app/download',{method:'HEAD'})).body,null);
assert.equal(androidRoute(new Request(origin+'/api/app/download',{method:'POST'})).status,405);
assert.equal(androidRoute(new Request(origin+'/api/app/unknown')).status,404);
assert.equal(androidRoute(new Request(origin+'/api/auth/me')),null);
assert.equal(androidRoute(new Request(origin+'/catalogo/')),null);
new vm.Script(appClient);
const html=await androidRoute(new Request(origin+'/api/app/install')).text();
assert.match(html,/não instala/);assert.match(html,/avisos de segurança/);assert.match(html,/<meta name="viewport"/);
const java=await readFile(new URL('../android/src/br/com/valenzaparfums/app/MainActivity.java',import.meta.url),'utf8');
assert.ok(!java.includes('addJavascriptInterface'));
assert.ok(!java.includes('handler.proceed'));
assert.match(java,/MIXED_CONTENT_NEVER_ALLOW/);
assert.match(java,/setAllowFileAccess\(false\)/);
assert.match(java,/getPort\(\)==443/);
const manifest=await readFile(new URL('../android/AndroidManifest.xml',import.meta.url),'utf8');
assert.match(manifest,/usesCleartextTraffic="false"/);
assert.deepEqual([...manifest.matchAll(/uses-permission android:name="([^"]+)"/g)].map(m=>m[1]),['android.permission.INTERNET']);
console.log('Android distribution: APK hash, headers, routes and security invariants passed.');
